begin;

create table if not exists public.tracking_sessions (
  id bigint generated by default as identity primary key,
  user_id text not null,
  course_id text not null check (course_id in ('cheonjusan', 'muhaksan', 'hwangmaesan', 'yongji')),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  start_lat double precision not null check (start_lat between -90 and 90),
  start_lng double precision not null check (start_lng between -180 and 180),
  end_lat double precision check (end_lat between -90 and 90),
  end_lng double precision check (end_lng between -180 and 180),
  check ((ended_at is null and end_lat is null and end_lng is null)
      or (ended_at is not null and end_lat is not null and end_lng is not null and ended_at >= started_at))
);

create unique index if not exists tracking_sessions_one_active_per_user
  on public.tracking_sessions (user_id) where ended_at is null;
create index if not exists tracking_sessions_user_started_idx
  on public.tracking_sessions (user_id, started_at desc);

create or replace function public.tracking_set_end_time()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.ended_at is not null then
    new.ended_at := now();
  end if;
  return new;
end
$$;
drop trigger if exists tracking_set_end_time on public.tracking_sessions;
create trigger tracking_set_end_time before update on public.tracking_sessions
  for each row execute function public.tracking_set_end_time();

alter table public.tracking_sessions enable row level security;
drop policy if exists "Users can read own tracking sessions" on public.tracking_sessions;
create policy "Users can read own tracking sessions"
  on public.tracking_sessions for select to authenticated
  using (user_id = (select auth.jwt()->>'sub'));
drop policy if exists "Users can start own tracking sessions" on public.tracking_sessions;
create policy "Users can start own tracking sessions"
  on public.tracking_sessions for insert to authenticated
  with check (user_id = (select auth.jwt()->>'sub') and ended_at is null);
drop policy if exists "Users can finish own tracking sessions" on public.tracking_sessions;
create policy "Users can finish own tracking sessions"
  on public.tracking_sessions for update to authenticated
  using (user_id = (select auth.jwt()->>'sub') and ended_at is null)
  with check (user_id = (select auth.jwt()->>'sub') and ended_at is not null);
revoke all on public.tracking_sessions from public, anon, authenticated;
grant select, insert on public.tracking_sessions to authenticated;
grant update (ended_at, end_lat, end_lng) on public.tracking_sessions to authenticated;
grant usage, select on sequence public.tracking_sessions_id_seq to authenticated;

commit;
